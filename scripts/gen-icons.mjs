// Writes packages/core/src/icons.ts: the few game-icons.net icons Lore-Forge uses, as SVG path data.
// Icons by Lorc, Delapouite and contributors, https://game-icons.net, CC BY 3.0. Run: node scripts/gen-icons.mjs
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const USED = [
  // entry types
  'person', 'castle', 'checked-shield', 'broadsword', 'crossed-swords', 'scroll-unfurled',
  // statuses
  'heart-beats', 'tombstone', 'uncertainty', 'castle-ruins', 'flying-flag', 'broken-shield', 'sparkles', 'broken-axe', 'fog',
  // relation groups
  'family-tree', 'shaking-hands', 'crown', 'backpack', 'position-marker', 'open-book', 'linked-rings', 'diamond-ring',
  // races and kinds
  'woman-elf-face', 'dwarf-face', 'orc-head', 'camel-head', 'daemon-skull', 'shambling-zombie', 'vampire-dracula', 'spectre', 'djinn', 'hood',
  // app
  'quill-ink', 'hourglass', 'sands-of-time', 'spider-web', 'book-cover', 'magnifying-glass', 'hazard-sign', 'cancel', 'check-mark', 'save', 'trash-can',
  'quill', 'photo-camera', 'palette', 'sprout', 'compass', 'pointing', 'laurels', 'magic-swirl', 'treasure-map', 'world', 'return-arrow',
  'info', 'stars-stack', 'scroll-quill', 'locked-chest', 'pencil', 'files', 'book-pile', 'fast-backward-button', 'fast-forward-button',
];

const require = createRequire(import.meta.url);
const set = require('@iconify-json/game-icons/icons.json');
const out = {};
for (const name of USED) {
  const icon = set.icons[name];
  if (!icon) throw new Error(`no game-icon named ${name}`);
  const rest = icon.body.replace(/<path\b[^>]*\bd="([^"]+)"[^>]*\/>/g, '');
  if (rest.trim()) throw new Error(`${name} has more than plain paths: ${rest.slice(0, 80)}`);
  out[name] = [...icon.body.matchAll(/\bd="([^"]+)"/g)].map((m) => m[1]);
}
const lines = Object.entries(out).map(([k, ds]) => `  '${k}': [${ds.map((d) => JSON.stringify(d)).join(', ')}],`);
writeFileSync(new URL('../packages/core/src/icons.ts', import.meta.url), `// Generated by scripts/gen-icons.mjs from @iconify-json/game-icons ${require('@iconify-json/game-icons/package.json').version}. Do not edit.
// Icons by Lorc, Delapouite and other game-icons.net authors, licensed CC BY 3.0 (https://creativecommons.org/licenses/by/3.0/).

/** SVG path data on a 512 x 512 canvas, filled with the current colour. */
export const ICONS = {
${lines.join('\n')}
} as const satisfies Record<string, readonly string[]>;

export type IconName = keyof typeof ICONS;

/** Side of the square the paths are drawn on. */
export const ICON_SIZE = 512;

export const ICON_CREDITS = {
  name: 'game-icons.net',
  url: 'https://game-icons.net',
  authors: 'Lorc, Delapouite and other game-icons.net contributors',
  license: 'CC BY 3.0',
  licenseUrl: 'https://creativecommons.org/licenses/by/3.0/',
} as const;
`);
console.log(`icons.ts: ${USED.length} icons`);
