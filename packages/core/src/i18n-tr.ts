/**
 * Turkish for everything core shows to people. Keys are the English texts: whole texts for fixed words and labels, and
 * template keys ("{0} can't {1} {2}: ...") for texts made with msg. Use with localize() and localizeDoc() (i18n.ts).
 *
 * How the Turkish is built:
 * - A placeholder never gets a suffix (a name's sound decides the suffix): "{0} adlı yerde", "{0} kaydında", "{0} için",
 *   "{0} tarafından", "{0} ile".
 * - Deeds are infinitives ("{0} adlı karakteri öldürmek"), so a message can say "… mümkün değil" around any of them.
 *   The object's case needs a noun for the kind of entry; "place\u0004kill {0}" is the same verb with a place as its
 *   object (the context is the entry type, see msgIn in i18n.ts). The plain key covers the usual kind.
 * - Life words are finished past tense ("öldü", "kuruldu"), dates come as "1800 yılında" / "12.03.1800 tarihinde".
 * - Relation labels name the other entry's role, the way Turkish lists relatives ("Çocuğu: Ilsa"): "parent of" is
 *   "çocuğu", so "Orsan, çocuğu: Ilsa" says that Orsan is Ilsa's parent. The inverse labels work the same way.
 */
import type { EntryType } from './types.ts';

const CTX = '\u0004';
const TYPES: readonly EntryType[] = ['character', 'place', 'faction', 'item', 'event', 'note'];
/** The kinds of entries as Turkish nouns in the cases verbs need. */
const NOUN: Record<EntryType, { acc: string; dat: string; gen: string }> = {
  character: { acc: 'karakteri', dat: 'karaktere', gen: 'karakterin' },
  place: { acc: 'yeri', dat: 'yere', gen: 'yerin' },
  faction: { acc: 'topluluğu', dat: 'topluluğa', gen: 'topluluğun' },
  item: { acc: 'eşyayı', dat: 'eşyaya', gen: 'eşyanın' },
  event: { acc: 'olayı', dat: 'olaya', gen: 'olayın' },
  note: { acc: 'notu', dat: 'nota', gen: 'notun' },
};

/** "kill {0}" -> "{0} adlı karakteri öldürmek", plus the same verb for every other kind of target. */
function onTarget(template: string, kase: 'acc' | 'dat' | 'gen', verb: string, usual: EntryType): Record<string, string> {
  const out: Record<string, string> = { [template]: `{0} adlı ${NOUN[usual][kase]} ${verb}` };
  for (const t of TYPES) if (t !== usual) out[`${t}${CTX}${template}`] = `{0} adlı ${NOUN[t][kase]} ${verb}`;
  return out;
}
/** Context variants written out: { place: '...', faction: '...' } -> "place\u0004template". */
function inContext(template: string, variants: Partial<Record<EntryType | 'relation', string>>): Record<string, string> {
  return Object.fromEntries(Object.entries(variants).map(([ctx, tr]) => [`${ctx}${CTX}${template}`, tr]));
}

